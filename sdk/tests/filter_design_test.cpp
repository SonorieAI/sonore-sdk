// ── Helpers ──────────────────────────────────────────────────────────────────

/** The amplitude of a symmetric kernel at `hz`, in double: the cosine sum
 *  about its centre. Measured here from the taps, never from the design. */
double amplitude(const std::vector<float>& h, double hz) {
  const double centre = (double) (h.size() - 1) * 0.5;
  double a = 0.0;
  for (size_t n = 0; n < h.size(); ++n)
    a += (double) h[n] * std::cos(2.0 * kPi * hz / kRate * ((double) n - centre));
  return a;
}

/** The largest |A - desired| * weight across [lo, hi], on `points` points. */
double bandError(const std::vector<float>& h, double lo, double hi, double desired, double weight,
                 int points = 4000) {
  double peak = 0.0;
  for (int i = 0; i < points; ++i) {
    const double f = lo + (hi - lo) * (double) i / (double) (points - 1);
    peak = std::fmax(peak, weight * std::fabs(amplitude(h, f) - desired));
  }
  return peak;
}

/** How many times the weighted error reaches (within 3% of) its peak with
 *  alternating signs, across the bands in order: the alternation theorem's
 *  count. `bands` are {lo, hi, desired, weight} in Hz. */
struct Band {
  double lo, hi, desired, weight;
};
int alternations(const std::vector<float>& h, const Band* bands, int count, double peak) {
  int n = 0;
  int lastSign = 0;
  for (int b = 0; b < count; ++b) {
    // Walk the band, and count each new excursion to the peak whose sign
    // differs from the previous one.
    const int points = 20000;
    for (int i = 0; i < points; ++i) {
      const double f = bands[b].lo + (bands[b].hi - bands[b].lo) * (double) i / (double) (points - 1);
      const double e = bands[b].weight * (bands[b].desired - amplitude(h, f));
      // Within 3% of the peak: the exchange levels the error on its design
      // grid, and the true extremum between two grid points runs a percent
      // or so over -- so the shallowest ripple reads that much under the
      // tallest, and a 1% threshold would not count it.
      if (std::fabs(e) < 0.97 * peak) continue;
      const int sign = e > 0.0 ? 1 : -1;
      if (sign != lastSign) {
        ++n;
        lastSign = sign;
      }
    }
  }
  return n;
}

/** The gain of an IIR at `hz`, MEASURED: a sine run through process() long
 *  enough to settle, its RMS against the input's, in dB. */
template <typename Filter>
double measuredGainDb(Filter& f, double hz) {
  f.reset();
  const int settle = 48000, measure = 48000;
  double in2 = 0.0, out2 = 0.0;
  for (int i = 0; i < settle + measure; ++i) {
    const float x = (float) std::sin(2.0 * kPi * hz * (double) i / kRate);
    const float y = f.process(x);
    if (i >= settle) {
      in2 += (double) x * x;
      out2 += (double) y * y;
    }
  }
  return 10.0 * std::log10(out2 / in2);
}

// ── Elliptic IIR ─────────────────────────────────────────────────────────────

void testElliptic() {
  std::printf("elliptic IIR\n");
  using namespace sonore;

  // The response, against scipy.signal.ellip with the same order, ripple,
  // rejection and passband edge (both prewarp the bilinear transform at the
  // edge, so they are the same filter, not merely similar ones).
  double worst = 0.0;
  for (const EllipticRef& ref : kEllipticRefs) {
    CascadedIir<8> f;
    f.setSampleRate((float) kRate);
    const bool ok = ref.highpass ? f.designEllipticHighpass(ref.freq, ref.order, ref.rippleDb, ref.stopbandDb)
                                 : f.designEllipticLowpass(ref.freq, ref.order, ref.rippleDb, ref.stopbandDb);
    if (!ok) worst = 1e9;
    for (int i = 0; i < 19; ++i) {
      const double ours = (double) f.magnitudeDb(kEllipticFreqs[i]);
      // magnitudeDb is a float: a thousandth of a dB is its resolution at
      // -116 dB, and a millionth in the passband.
      const double tolerance = 1e-3 + 1e-5 * std::fabs(ref.db[i]);
      worst = std::fmax(worst, std::fabs(ours - ref.db[i]) / tolerance);
    }
  }
  check(worst <= 1.0, "five elliptic designs, low- and highpass, orders 3 to 8: scipy's response at 19 frequencies");

  // The defining properties, measured on the filter: the passband ripples
  // between 0 and -Ap and is exactly -Ap at its edge, the stopband never
  // rises above -As, and -- equiripple in BOTH bands -- an order-N lowpass
  // reaches 0 dB ceil(N/2) times in its passband.
  {
    CascadedIir<8> f;
    f.setSampleRate((float) kRate);
    f.designEllipticLowpass(2000.0f, 7, 0.5f, 70.0f);
    double passMax = -1e9, passMin = 1e9;
    int peaks = 0;
    double previous = -1e9, previousSlope = 0.0;
    for (int i = 0; i <= 4000; ++i) {
      const double hz = 2000.0 * (double) i / 4000.0;
      const double db = (double) f.magnitudeDb((float) hz);
      passMax = std::fmax(passMax, db);
      passMin = std::fmin(passMin, db);
      const double slope = db - previous;
      if (i > 1 && previousSlope > 0.0 && slope <= 0.0 && db > -0.01) ++peaks;
      previousSlope = slope;
      previous = db;
    }
    if ((double) f.magnitudeDb(0.0f) > -0.01) ++peaks; // DC is one for an odd order
    check(passMax <= 1e-4 && passMin >= -0.5 - 1e-3, "order 7: the passband stays between 0 and -0.5 dB");
    check(std::fabs((double) f.magnitudeDb(2000.0f) + 0.5) < 1e-3, "and is exactly -0.5 dB at its edge");
    check(peaks == 4, "and touches 0 dB four times: equiripple, ceil(7 / 2) peaks");
    // The stopband edge the degree equation puts it at: 1/k on the
    // prototype, mapped back through the prewarp.
    const double ep = iirEpsilon(0.5), es = iirEpsilon(70.0);
    const double k = ellipticDegree(7, ep / es);
    const double edge = std::atan(std::tan(kPi * 2000.0 / kRate) / k) * kRate / kPi;
    double stopMax = -1e9;
    for (int i = 0; i <= 4000; ++i) {
      const double hz = edge + (kRate * 0.5 - edge) * (double) i / 4000.0;
      stopMax = std::fmax(stopMax, (double) f.magnitudeDb((float) hz));
    }
    check(stopMax <= -70.0 + 1e-3, "and from the stopband edge on it never rises above -70 dB");
    check(std::fabs((double) f.magnitudeDb((float) edge) + 70.0) < 0.01, "reaching exactly -70 dB at that edge");
  }

  // What process() does is what magnitudeDb() says: a sine, measured.
  {
    CascadedIir<8> f;
    f.setSampleRate((float) kRate);
    f.designEllipticLowpass(1000.0f, 6, 0.2f, 60.0f);
    const double pass = measuredGainDb(f, 700.0), stop = measuredGainDb(f, 5000.0);
    check(std::fabs(pass - (double) f.magnitudeDb(700.0f)) < 0.01 &&
              std::fabs(stop - (double) f.magnitudeDb(5000.0f)) < 0.05,
          "a sine through process() measures the designed gain, pass and stop");
    // A corner far below the rate is where a float coefficient would lose
    // it; the sections are double, so a 30 Hz order-8 highpass holds.
    CascadedIir<8> low;
    low.setSampleRate(192000.0f);
    low.designEllipticHighpass(30.0f, 8, 0.1f, 80.0f);
    check(std::fabs((double) low.magnitudeDb(30.0f) + 0.1) < 1e-3, "30 Hz at 192 kHz, order 8: -0.1 dB at its edge");
    // Its poles sit within a few hertz of DC with a Q in the tens, so its
    // ring-down takes seconds -- which is the filter, not a fault. Stable is
    // what can be asked: second by second, the impulse response only falls.
    low.reset();
    float peaks[10] = {};
    for (int i = 0; i < 192000 * 10; ++i) {
      const float y = low.process(i == 0 ? 1.0f : 0.0f);
      peaks[i / 192000] = std::fmax(peaks[i / 192000], std::fabs(y));
    }
    bool falling = peaks[9] < 1e-5f * peaks[0];
    for (int s = 1; s < 10; ++s)
      if (peaks[s - 1] > 1e-20f && !(peaks[s] < peaks[s - 1])) falling = false; // until the 1e-30 state floor
    check(falling, "and its impulse response falls every second, 100 dB in ten");
  }

  // Refusals leave the filter as it was.
  {
    CascadedIir<8> f;
    f.setSampleRate((float) kRate);
    f.designEllipticLowpass(1000.0f, 4, 0.5f, 60.0f);
    const float before = f.magnitudeDb(1500.0f);
    const bool refused = !f.designEllipticLowpass(1000.0f, 9, 0.5f, 60.0f) &&   // past MaxOrder
                         !f.designEllipticLowpass(1000.0f, 4, 60.0f, 50.0f) &&  // rejection under ripple
                         !f.designEllipticLowpass(1000.0f, 4, 0.0f, 50.0f) &&   // no ripple
                         !f.designEllipticLowpass(30000.0f, 4, 0.5f, 60.0f);    // past Nyquist
    check(refused && f.magnitudeDb(1500.0f) == before, "impossible elliptic designs are refused, the filter unchanged");
  }
}

// ── Designing an IIR to a specification ──────────────────────────────────────

void testIirToSpec() {
  std::printf("IIR to a specification\n");
  using namespace sonore;

  // The minimum orders, against scipy's buttord / cheb1ord / cheb2ord /
  // ellipord: five specifications, lowpass and highpass, ripple 0.01 to 3 dB.
  bool same = true;
  for (const OrderRef& ref : kOrderRefs) {
    const int ours[4] = {iirOrderFor(IirFamily::Butterworth, ref.pass, ref.stop, kRate, ref.ripple, ref.rejection),
                         iirOrderFor(IirFamily::Chebyshev1, ref.pass, ref.stop, kRate, ref.ripple, ref.rejection),
                         iirOrderFor(IirFamily::Chebyshev2, ref.pass, ref.stop, kRate, ref.ripple, ref.rejection),
                         iirOrderFor(IirFamily::Elliptic, ref.pass, ref.stop, kRate, ref.ripple, ref.rejection)};
    const int theirs[4] = {ref.butterworth, ref.chebyshev1, ref.chebyshev2, ref.elliptic};
    for (int i = 0; i < 4; ++i)
      if (ours[i] != theirs[i]) {
        same = false;
        std::printf("       %g/%g Hz %g/%g dB family %d: %d, scipy %d\n", ref.pass, ref.stop, ref.ripple,
                    ref.rejection, i, ours[i], theirs[i]);
      }
  }
  check(same, "the minimum order of all four families: scipy's, for all five specifications");

  // Every family, designed to one spec, MEETS it -- measured on the filter.
  // 0.5 dB to 3 kHz, 60 dB from 4 kHz: Butterworth needs 26 (refused at
  // MaxOrder 8 below), the others 9, 9 and 5.
  const IirFamily families[4] = {IirFamily::Butterworth, IirFamily::Chebyshev1, IirFamily::Chebyshev2,
                                 IirFamily::Elliptic};
  const char* names[4] = {"Butterworth", "Chebyshev I", "Chebyshev II", "elliptic"};
  for (int i = 0; i < 4; ++i) {
    for (int hp = 0; hp < 2; ++hp) {
      CascadedIir<16> f;
      f.setSampleRate((float) kRate);
      const float pass = hp ? 4000.0f : 3000.0f, stop = hp ? 3000.0f : 4000.0f;
      const int order = hp ? f.designHighpassToSpec(families[i], pass, stop, 0.5f, 60.0f)
                           : f.designLowpassToSpec(families[i], pass, stop, 0.5f, 60.0f);
      double passWorst = 0.0, stopWorst = -1e9;
      for (int k = 0; k <= 3000; ++k) {
        const double p = hp ? 4000.0 + (kRate * 0.5 - 4000.0) * k / 3000.0 : 3000.0 * k / 3000.0;
        const double s = hp ? 3000.0 * k / 3000.0 : 4000.0 + (kRate * 0.5 - 4000.0) * k / 3000.0;
        passWorst = std::fmin(passWorst, (double) f.magnitudeDb((float) p));
        stopWorst = std::fmax(stopWorst, (double) f.magnitudeDb((float) s));
      }
      const int expected = iirOrderFor(families[i], pass, stop, kRate, 0.5, 60.0);
      char what[160];
      std::snprintf(what, sizeof what, "%s %s to spec: order %d (%d expected), passband >= -0.5 dB, stopband <= -60 dB",
                    names[i], hp ? "highpass" : "lowpass", order, expected);
      if (expected > 16) {
        check(order == 0, "Butterworth past MaxOrder is refused (0), never delivered shallower");
      } else {
        check(order == expected && passWorst >= -0.5 - 2e-3 && stopWorst <= -60.0 + 2e-3, what);
      }
    }
  }
  CascadedIir<4> small;
  small.setSampleRate((float) kRate);
  check(small.designLowpassToSpec(IirFamily::Elliptic, 3000.0f, 4000.0f, 0.5f, 60.0f) == 0,
        "an order past MaxOrder is refused rather than clamped");
  check(small.designLowpassToSpec(IirFamily::Elliptic, 4000.0f, 3000.0f, 0.5f, 60.0f) == 0,
        "a lowpass whose stopband edge is below its passband edge is refused");
}

// ── Least-squares FIR ────────────────────────────────────────────────────────

void testLeastSquares() {
  std::printf("least-squares FIR\n");
  using namespace sonore;
  FirFilter f;
  const FirBand bands[2] = {{0.0f, 8000.0f, 1.0f, 1.0f}, {10000.0f, 24000.0f, 0.0f, 10.0f}};
  check(f.designLeastSquares(bands, 2, (float) kRate, 61), "a 61-tap, two-band least-squares design");
  const std::vector<float>& h = f.coefficients();
  double worst = 0.0;
  for (int i = 0; i < 31; ++i) {
    worst = std::fmax(worst, std::fabs((double) h[(size_t) i] - kFirlsRef[i]));
    worst = std::fmax(worst, std::fabs((double) h[(size_t) (60 - i)] - kFirlsRef[i]));
  }
  check(h.size() == 61 && worst < 1e-7, "is scipy.signal.firls's kernel, tap for tap (to float precision)");

  // Optimality, without scipy: the error energy is a quadratic with its
  // minimum at the design, so nudging any tap pair either way must raise it.
  auto energy = [&](const std::vector<float>& k) {
    double e = 0.0;
    for (int i = 0; i < 2000; ++i) {
      const double p = 8000.0 * i / 1999.0, s = 10000.0 + 14000.0 * i / 1999.0;
      const double ep = amplitude(k, p) - 1.0, es = amplitude(k, s);
      e += ep * ep * 8000.0 + 10.0 * es * es * 14000.0;
    }
    return e;
  };
  const double best = energy(h);
  bool minimal = true;
  for (int tap = 0; tap < 30; tap += 7)
    for (double nudge : {-2e-4, 2e-4}) {
      std::vector<float> k = h;
      k[(size_t) tap] += (float) nudge;
      k[(size_t) (60 - tap)] += (float) nudge;
      if (energy(k) <= best) minimal = false;
    }
  check(minimal, "and nudging any tap pair raises its weighted error energy: a minimum");

  FirFilter g;
  check(g.designLowpassLeastSquares(6000.0f, (float) kRate, 101, 2000.0f, 5.0f) &&
            std::fabs(amplitude(g.coefficients(), 0.0) - 1.0) < 1e-3 &&
            bandError(g.coefficients(), 7000.0, 24000.0, 0.0, 1.0) < 1e-3,
        "designLowpassLeastSquares: unity at DC, the stopband under -60 dB");
  const FirBand overlapping[2] = {{0.0f, 9000.0f, 1.0f, 1.0f}, {8000.0f, 24000.0f, 0.0f, 1.0f}};
  check(!g.designLeastSquares(overlapping, 2, (float) kRate, 61) && g.numTaps() == 101,
        "overlapping bands are refused, the kernel unchanged");
}

// ── Equiripple (Parks-McClellan) FIR ─────────────────────────────────────────

void testEquiripple() {
  std::printf("equiripple FIR (Parks-McClellan)\n");
  using namespace sonore;

  // The lowpass scipy's remez designs, held to its result: our peak
  // weighted error must be no worse than the reference implementation's.
  {
    FirFilter f;
    const FirBand bands[2] = {{0.0f, 8000.0f, 1.0f, 1.0f}, {10000.0f, 24000.0f, 0.0f, 10.0f}};
    const double deviation = f.designEquiripple(bands, 2, (float) kRate, 61);
    const std::vector<float>& h = f.coefficients();
    const double peak = std::fmax(bandError(h, 0.0, 8000.0, 1.0, 1.0, 20000),
                                  bandError(h, 10000.0, 24000.0, 0.0, 10.0, 20000));
    check(deviation > 0.0 && peak <= kRemezRefPeak * 1.0001,
          "61-tap lowpass: a peak weighted error no worse than scipy.signal.remez's");
    // The alternation theorem: optimal iff the weighted error reaches its
    // peak, alternating in sign, at least r + 1 = 32 times.
    const Band b[2] = {{0.0, 8000.0, 1.0, 1.0}, {10000.0, 24000.0, 0.0, 10.0}};
    const int n = alternations(h, b, 2, peak);
    char what[128];
    std::snprintf(what, sizeof what, "and its error alternates %d times at the peak: at least 32, so it is the optimum", n);
    check(n >= 32, what);
    check(std::fabs(peak - deviation) < 0.02 * deviation, "the deviation it returns is the peak measured on the taps");
  }

  // A bandpass, three bands.
  {
    FirFilter f;
    const FirBand bands[3] = {{0.0f, 3000.0f, 0.0f, 1.0f}, {5000.0f, 9000.0f, 1.0f, 1.0f},
                              {11000.0f, 24000.0f, 0.0f, 1.0f}};
    const double deviation = f.designEquiripple(bands, 3, (float) kRate, 101);
    const std::vector<float>& h = f.coefficients();
    const double peak = std::fmax(std::fmax(bandError(h, 0.0, 3000.0, 0.0, 1.0, 20000),
                                            bandError(h, 5000.0, 9000.0, 1.0, 1.0, 20000)),
                                  bandError(h, 11000.0, 24000.0, 0.0, 1.0, 20000));
    const Band b[3] = {{0.0, 3000.0, 0.0, 1.0}, {5000.0, 9000.0, 1.0, 1.0}, {11000.0, 24000.0, 0.0, 1.0}};
    check(deviation > 0.0 && peak <= kRemezBandpassRefPeak * 1.0001 && alternations(h, b, 3, peak) >= 52,
          "101-tap bandpass: no worse than scipy's, and 52 alternations certify it optimal");
  }

  // Long designs. The exchange carries its polynomial in barycentric form
  // with the weights in logarithms and moves each extremal only within its
  // own interval: a 2001-tap lowpass at about 120 dB converges, which the
  // classic program (and scipy's port of it) does not at 1601 taps.
  {
    FirFilter f;
    const double df = (120.0 - 13.0) / (14.6 * 2000.0);
    const float half = (float) (df * kRate * 0.5);
    const FirBand bands[2] = {{0.0f, 10000.0f - half, 1.0f, 1.0f}, {10000.0f + half, 24000.0f, 0.0f, 1.0f}};
    const double deviation = f.designEquiripple(bands, 2, (float) kRate, 2001);
    const double stop = bandError(f.coefficients(), 10000.0 + half, 24000.0, 0.0, 1.0, 6000);
    check(deviation > 0.0 && deviation < 2e-6 && stop < 1.03 * deviation,
          "2001 taps, a 70 Hz transition: converges to ~118 dB, and the taps measure it");
  }

  // To a specification: the shortest kernel that meets it, measured.
  {
    FirFilter f;
    const size_t taps = f.designEquirippleLowpassToSpec(18000.0f, 20000.0f, (float) kRate, 0.1f, 80.0f);
    const std::vector<float>& h = f.coefficients();
    double pmax = -1e9, pmin = 1e9;
    for (int i = 0; i < 6000; ++i) {
      const double a = amplitude(h, 18000.0 * i / 5999.0);
      pmax = std::fmax(pmax, a);
      pmin = std::fmin(pmin, a);
    }
    const double rippleDb = 20.0 * std::log10(pmax / pmin);
    const double stopDb = 20.0 * std::log10(bandError(h, 20000.0, 24000.0, 0.0, 1.0, 6000));
    char what[160];
    std::snprintf(what, sizeof what, "0.1 dB to 18 kHz, 80 dB from 20 kHz: %zu taps, ripple %.3f dB, stopband %.1f dB",
                  taps, rippleDb, stopDb);
    check(taps > 0 && rippleDb <= 0.1 && stopDb <= -80.0, what);
    FirFilter shorter;
    const FirBand bands[2] = {{0.0f, 18000.0f, 1.0f, 1.0f}, {20000.0f, 24000.0f, 0.0f, 1.0f}};
    shorter.designEquiripple(bands, 2, (float) kRate, taps - 2);
    // The same spec at two taps fewer fails it, whatever the weighting --
    // checked at the weight the design itself used.
    const double g = std::pow(10.0, 0.1 / 20.0), dp = (g - 1.0) / (g + 1.0), ds = std::pow(10.0, -4.0);
    const FirBand weighted[2] = {{0.0f, 18000.0f, 1.0f, 1.0f}, {20000.0f, 24000.0f, 0.0f, (float) (dp / ds)}};
    const double fewer = shorter.designEquiripple(weighted, 2, (float) kRate, taps - 2);
    check(fewer > dp, "and two taps fewer cannot meet it: it is the shortest");
    FirFilter kaiser;
    const size_t kaiserTaps = kaiser.designLowpassToSpec(19000.0f, (float) kRate, 2000.0f, 80.0f);
    std::snprintf(what, sizeof what, "the Kaiser window needs %zu taps for the same 80 dB across the same 2 kHz", kaiserTaps);
    check(kaiserTaps > taps + taps / 4, what);
  }

  // Refusals.
  {
    FirFilter f;
    f.designLowpass(1000.0f, (float) kRate, 31);
    const FirBand overlapping[2] = {{0.0f, 9000.0f, 1.0f, 1.0f}, {8000.0f, 24000.0f, 0.0f, 1.0f}};
    const FirBand outside[1] = {{0.0f, 30000.0f, 1.0f, 1.0f}};
    const FirBand weightless[1] = {{0.0f, 9000.0f, 1.0f, 0.0f}};
    check(f.designEquiripple(overlapping, 2, (float) kRate, 61) < 0.0 &&
              f.designEquiripple(outside, 1, (float) kRate, 61) < 0.0 &&
              f.designEquiripple(weightless, 1, (float) kRate, 61) < 0.0 && f.numTaps() == 31,
          "overlapping bands, a band past Nyquist and a zero weight are refused, the kernel unchanged");
    check(f.designEquirippleLowpassToSpec(18000.0f, 18001.0f, (float) kRate, 0.001f, 150.0f) == 0 && f.numTaps() == 31,
          "a spec no kernel within the tap limit meets is refused (0)");
  }
}

// ── Half-band ────────────────────────────────────────────────────────────────

void testHalfBand() {
  std::printf("equiripple half-band\n");
  using namespace sonore;
  FirFilter f;
  const float rejection = f.designHalfBand(4800.0f, (float) kRate, 31);
  const std::vector<float>& h = f.coefficients();
  bool structure = h.size() == 31 && h[15] == 0.5f;
  for (size_t i = 0; i < h.size(); ++i) {
    if (h[i] != h[h.size() - 1 - i]) structure = false;
    // Every tap an even distance from the centre is zero, the centre aside.
    if (i != 15 && ((i + 15) % 2) == 0 && h[i] != 0.0f) structure = false;
  }
  check(structure, "31 taps: symmetric, 1/2 at the centre, every other tap exactly zero");
  const double stop = bandError(h, 14400.0, 24000.0, 0.0, 1.0, 20000);
  const double pass = bandError(h, 0.0, 9600.0, 1.0, 1.0, 20000);
  check(std::fabs(-20.0 * std::log10(stop) - (double) rejection) < 0.1,
        "the rejection it reports is the stopband peak measured on the taps (within 0.1 dB)");
  check(std::fabs(pass - stop) < 0.01 * stop, "passband ripple and stopband rejection are one number, as a half-band's are");
  // Symmetric about fs/4: |H(f)| + |H(fs/2 - f)| = 1 for a half-band.
  bool complementary = true;
  for (int i = 0; i <= 100; ++i) {
    const double hz = 12000.0 * i / 100.0;
    if (std::fabs(amplitude(h, hz) + amplitude(h, 24000.0 - hz) - 1.0) > 1e-6) complementary = false;
  }
  check(complementary, "and A(f) + A(fs/2 - f) = 1 at every frequency");
  const Band b[2] = {{0.0, 9600.0, 1.0, 1.0}, {14400.0, 24000.0, 0.0, 1.0}};
  check(alternations(h, b, 2, std::fmax(pass, stop)) >= 9, "its error alternates at least m + 1 = 9 times: optimal");

  const size_t taps = f.designHalfBandToSpec(2400.0f, (float) kRate, 100.0f);
  const double specStop = 20.0 * std::log10(bandError(f.coefficients(), 13200.0, 24000.0, 0.0, 1.0, 20000));
  char what[128];
  std::snprintf(what, sizeof what, "100 dB across 2.4 kHz: %zu taps (4m - 1), measured %.1f dB", taps, specStop);
  check(taps > 0 && (taps + 1) % 4 == 0 && specStop <= -100.0, what);
  FirFilter shorter;
  const float shorterRejection = shorter.designHalfBand(2400.0f, (float) kRate, taps - 4);
  check(shorterRejection < 100.0f, "and the next shorter half-band does not reach it");
}

// ── Windows ──────────────────────────────────────────────────────────────────

void testWindows() {
  std::printf("triangular and Kaiser windows\n");
  using namespace sonore;
  std::vector<float> w(101);
  fillWindow(w.data(), w.size(), Window::Triangular);
  bool linear = w[0] == 0.0f && w[100] == 0.0f && w[50] == 1.0f;
  for (size_t i = 0; i <= 50; ++i)
    if (std::fabs(w[i] - (float) i / 50.0f) > 1e-6f || w[i] != w[100 - i]) linear = false;
  check(linear, "triangular: zero at both ends, 1 in the middle, a straight line between");

  fillWindow(w.data(), w.size(), Window::Kaiser, 0.0);
  bool rect = true;
  for (float v : w)
    if (v != 1.0f) rect = false;
  check(rect, "Kaiser with beta 0 is the rectangle");
  fillWindow(w.data(), w.size(), Window::Kaiser, 8.6);
  bool same = true;
  for (size_t i = 0; i < w.size(); ++i)
    if (std::fabs((double) w[i] - special::kaiser(2.0 * (double) i / 100.0 - 1.0, 8.6)) > 1e-7) same = false;
  check(same && w[50] == 1.0f, "Kaiser with beta 8.6 is special::kaiser's shape, the one FIR design uses");

  // Its sidelobes, measured: the Kaiser window's transform, read far from the
  // main lobe, against the -60 dB beta 8 is known for (-58 is the textbook
  // figure for 8; 8.6 sits lower).
  std::vector<float> k(64);
  fillWindow(k.data(), k.size(), Window::Kaiser, 8.6);
  double main = 0.0, side = 0.0;
  for (int i = 0; i <= 4000; ++i) {
    const double f = 0.5 * i / 4000.0; // cycles per sample
    double re = 0.0, im = 0.0;
    for (size_t n = 0; n < k.size(); ++n) {
      re += (double) k[n] * std::cos(2.0 * kPi * f * (double) n);
      im -= (double) k[n] * std::sin(2.0 * kPi * f * (double) n);
    }
    const double mag = std::sqrt(re * re + im * im);
    if (i == 0) main = mag;
    else if (f > 6.0 / 64.0) side = std::fmax(side, mag);
  }
  check(20.0 * std::log10(side / main) < -60.0, "and its sidelobes sit below -60 dB");
}

