static void testBigIntegerModular() {
  std::printf("\nBigInteger: modular arithmetic\n");
  // exponentModulo against repeated multiplication, where repeated
  // multiplication is affordable.
  bool small = true;
  for (int i = 0; i < 3000; ++i) {
    const int64_t base = (int64_t) (rng() % 2000) - 1000, mod = 2 + (int64_t) (rng() % 1000000);
    const int exponent = (int) (rng() % 60);
    int64_t expect = 1 % mod, b = ((base % mod) + mod) % mod;
    for (int k = 0; k < exponent; ++k) expect = expect * b % mod;
    BigInteger v(base);
    v.exponentModulo(BigInteger(exponent), BigInteger(mod));
    small = small && v.toInt64() == expect;
  }
  check(small, "exponentModulo == repeated multiplication for 3,000 small cases, negative bases included");

  BigInteger edge(5);
  edge.exponentModulo(0, 7);
  bool edges = edge == 1;
  edge = 5;
  edge.exponentModulo(3, 1);
  edges = edges && edge.isZero();
  edge = 3;
  edge.exponentModulo(-1, 7); // 3 * 5 = 15 = 1 mod 7
  edges = edges && edge == 5;
  edge = 6;
  edge.exponentModulo(-1, 9); // no inverse
  edges = edges && edge.isZero();
  check(edges, "x^0 is 1, anything mod 1 is 0, a negative exponent is the inverse, and zero when none exists");

  // Against license.h's BigInt: written separately, for one job, with a
  // bit-serial reduction instead of Algorithm D. Agreement on random 64- to
  // 1024-bit operands is two implementations agreeing, not one agreeing
  // with itself.
  bool licence = true;
  for (int i = 0; i < 24; ++i) {
    const int bits = 64 + (int) (rng() % 961);
    BigInteger base = randomBig(bits + 40, false), exponent = randomBig(bits, false), mod = randomBig(bits, false);
    mod.setBit(bits - 1);
    using LicenceInt = sonore::license::BigInt;
    const LicenceInt theirs = LicenceInt::powMod(LicenceInt::fromHex(base.toString(16)),
                                                 LicenceInt::fromHex(exponent.toString(16)),
                                                 LicenceInt::fromHex(mod.toString(16)));
    base.exponentModulo(exponent, mod);
    licence = licence && LicenceInt::fromHex(base.toString(16)) == theirs;
  }
  check(licence, "exponentModulo agrees with license.h's independent BigInt on 24 random cases to 1024 bits");

  bool gcdOk = true, inverseOk = true;
  for (int i = 0; i < 400; ++i) {
    const BigInteger common = randomBig(1 + (int) (rng() % 100), false) + 1;
    const BigInteger a = randomBig((int) (rng() % 600), true) * common;
    const BigInteger b = randomBig(1 + (int) (rng() % 600), true) * common;
    if (b.isZero()) continue;
    const BigInteger g = a.findGreatestCommonDivisor(b);
    gcdOk = gcdOk && !g.isNegative() && (a % g).isZero() && (b % g).isZero() && (g % common).isZero();
    if (!a.isZero()) gcdOk = gcdOk && (a / g).findGreatestCommonDivisor(b / g).isOne();

    BigInteger m = randomBig(2 + (int) (rng() % 700), false) + 2, x = randomBig(700, true);
    BigInteger inv(x);
    inv.inverseModulo(m);
    if (x.findGreatestCommonDivisor(m).isOne()) {
      BigInteger product = x * inv;
      product %= m;
      if (product.isNegative()) product += m;
      inverseOk = inverseOk && product.isOne() && !inv.isNegative() && inv < m;
    } else {
      inverseOk = inverseOk && inv.isZero();
    }
  }
  check(gcdOk, "gcd divides both, is a multiple of a planted common factor, and leaves coprime cofactors");
  check(inverseOk, "x * inverse == 1 (mod m) in [0, m) where gcd is 1; zero exactly where it is not");
  check(BigInteger(0).findGreatestCommonDivisor(0).isZero() && BigInteger(-12).findGreatestCommonDivisor(18) == 6,
        "gcd(0, 0) is 0 and gcd ignores signs");
}

// ── Primes ──────────────────────────────────────────────────────────────────

static void testPrimes() {
  std::printf("\nPrimes\n");
  const int limit = 50000;
  std::vector<bool> composite((size_t) limit, false);
  composite[0] = composite[1] = true;
  for (int i = 2; i * i < limit; ++i)
    if (!composite[(size_t) i])
      for (int j = i * i; j < limit; j += i) composite[(size_t) j] = true;
  bool sieve = true;
  for (int n = -5; n < limit; ++n) {
    const bool expect = n >= 0 && !composite[(size_t) n];
    if (Primes::isProbablyPrime(BigInteger(n), 10) != expect) {
      std::printf("  (disagrees at %d)\n", n);
      sieve = false;
    }
  }
  check(sieve, "isProbablyPrime agrees with a sieve for every n below 50,000 (and says no to negatives)");

  // Around 2^32, where the trial division stops proving anything and the
  // deterministic Miller-Rabin bases take over, against trial division.
  bool near32 = true;
  for (uint64_t n = 4294967000ull; n < 4294969000ull; ++n) {
    bool prime = n % 2 != 0;
    for (uint64_t d = 3; prime && d * d <= n; d += 2) prime = n % d != 0;
    near32 = near32 && Primes::isProbablyPrime(BigInteger(n), 10) == prime;
  }
  check(near32, "...and with trial division for 2,000 consecutive numbers across 2^32");

  // 2^64 - 59 is the largest prime below 2^64, the edge of the deterministic
  // base set; the Mersenne exponents are the primes' own.
  bool knownPrimes = Primes::isProbablyPrime(parse("18446744073709551557", 10), 20);
  for (int exponent : {31, 61, 89, 107, 127, 521, 607}) {
    if (!Primes::isProbablyPrime((BigInteger(1) << exponent) - 1, 20)) {
      std::printf("  (2^%d - 1 called composite)\n", exponent);
      knownPrimes = false;
    }
  }
  bool mersenneComposites = true;
  for (int exponent : {11, 23, 29, 37, 41, 43, 47, 53, 59, 67, 71, 73, 79, 83, 97, 101, 103, 109, 113})
    mersenneComposites = mersenneComposites && !Primes::isProbablyPrime((BigInteger(1) << exponent) - 1, 20);
  check(knownPrimes, "Mersenne primes 2^31-1 to 2^607-1, and 2^64-59, are prime");
  check(mersenneComposites, "...and the 19 composite Mersenne numbers between, prime exponents and all, are not");

  const char* composites[] = {
      "18446744073709551615",      // 2^64 - 1
      "147573952589676412927",     // 2^67 - 1 = 193707721 * 761838257287
      "340282366920938463463374607431768211457", // 2^128 + 1, the seventh Fermat number
      "3215031751",                // a strong pseudoprime to bases 2, 3, 5 and 7
      "3825123056546413051",       // ...to every prime base up to 23
      "318665857834031151167461",  // ...to every prime base up to 37, and above 2^64
      "3317044064679887385961981", // ...to every prime base up to 41
      "95635931083302480072049",   // a Chernick Carmichael number, (6k+1)(12k+1)(18k+1), above 2^64
      nullptr};
  bool knownComposites = true;
  for (int i = 0; composites[i]; ++i) {
    if (Primes::isProbablyPrime(parse(composites[i], 10), 30)) {
      std::printf("  (called %s prime)\n", composites[i]);
      knownComposites = false;
    }
  }
  check(knownComposites, "2^64-1, 2^67-1, 2^128+1 and five pseudoprimes built to fool fixed bases are composite");

  // Carmichael numbers: every base coprime to them is a Fermat liar.
  const int carmichael[] = {561,    1105,   1729,   2465,   2821,   6601,   8911,   41041,  62745,  63973,
                            75361,  101101, 115921, 126217, 162401, 172081, 188461, 252601, 278545, 294409,
                            314821, 334153, 340561, 399001, 410041, 449065, 488881, 512461};
  bool carmichaelOk = true;
  for (int n : carmichael) carmichaelOk = carmichaelOk && !Primes::isProbablyPrime(BigInteger(n), 30);
  check(carmichaelOk, "the first 28 Carmichael numbers are composite");

  // A 318665857834031151167461 passes all twelve fixed bases: it is only
  // caught by the random ones. Many runs, so a fixed-base regression that
  // happens to pass once cannot hide.
  int caught = 0;
  const BigInteger spsp = parse("318665857834031151167461", 10);
  // Twenty rounds each: this number has the p(2p-1) shape that comes close
  // to MR's worst case of one liar base in four, so fewer would flake.
  for (int i = 0; i < 50; ++i) caught += Primes::isProbablyPrime(spsp, 20) ? 0 : 1;
  check(caught == 50, "the pseudoprime to all twelve fixed bases is caught by the random bases, 50 runs of 50");

  bool generated = true;
  for (int bits : {2, 3, 5, 8, 16, 17, 31, 64, 65, 127, 256, 512}) {
    const BigInteger p = Primes::createProbablePrime(bits, 20);
    bool exact = p.getHighestBit() == bits - 1 && Primes::isProbablyPrime(p, 20);
    if (bits <= 32) {
      const uint64_t v = (uint64_t) p.toInt64();
      for (uint64_t d = 2; exact && d * d <= v; ++d) exact = v % d != 0;
    }
    if (!exact) std::printf("  (%d bits: %s)\n", bits, p.toString(16).c_str());
    generated = generated && exact;
  }
  check(generated, "createProbablePrime makes primes of exactly 2, 3, 5, 8, 16, 17, 31, 64, 65, 127, 256 and 512 bits");
  const int seeds[] = {1, 2, 3, 4};
  const int other[] = {1, 2, 3, 5};
  const BigInteger s1 = Primes::createProbablePrime(256, 20, seeds, 4);
  const BigInteger s2 = Primes::createProbablePrime(256, 20, seeds, 4);
  const BigInteger s3 = Primes::createProbablePrime(256, 20, other, 4);
  check(s1 == s2 && s1 != s3 && Primes::isProbablyPrime(s3, 20),
        "with seeds it is a function of them: same seeds, same prime; one seed changed, another");
  check(Primes::createProbablePrime(1, 10).isZero() && Primes::createProbablePrime(0, 10).isZero(),
        "a prime of fewer than 2 bits is zero, not a guess");
}

// ── RSAKey ──────────────────────────────────────────────────────────────────

static void testRsa(int bits) {
  std::printf("\nRSAKey at %d bits\n", bits);
  RSAKey publicKey, privateKey;
  check(RSAKey::createKeyPair(publicKey, privateKey, bits), "createKeyPair, from the operating system's RNG");
  check(publicKey.isValid() && privateKey.isValid() && publicKey.modulus() == privateKey.modulus(),
        "...two valid keys sharing one modulus");
  check(publicKey.modulus().getHighestBit() == bits - 1, "...a modulus of exactly the asked-for bits");
  check(publicKey.exponent() == 65537, "...and the public exponent 65537");

  bool roundTrip = true;
  for (int i = 0; i < 20; ++i) {
    BigInteger message = randomBig(bits - 1, false) + 1;
    const BigInteger original(message);
    roundTrip = roundTrip && publicKey.applyToValue(message) && message != original && message < publicKey.modulus();
    roundTrip = roundTrip && privateKey.applyToValue(message) && message == original;
    roundTrip = roundTrip && privateKey.applyToValue(message) && publicKey.applyToValue(message) && message == original;
  }
  check(roundTrip, "20 values below the modulus: public then private, and private then public, give them back");

  // A value several moduli long, handled digit by digit as the reference does.
  BigInteger longValue = randomBig(bits * 3 + 17, false);
  if ((longValue % publicKey.modulus()).isZero()) longValue += 1;
  BigInteger work(longValue);
  check(publicKey.applyToValue(work) && privateKey.applyToValue(work) && work == longValue,
        "a value three moduli long round-trips too");

  // The digit order, which is what makes this the reference's format: the
  // lowest base-n digit comes out as the highest.
  const BigInteger& n = publicKey.modulus();
  const BigInteger d0 = randomBig(bits - 8, false) + 1, d1 = randomBig(bits - 8, false) + 1;
  BigInteger twoDigits = d0 + d1 * n;
  BigInteger e0(d0), e1(d1);
  e0.exponentModulo(publicKey.exponent(), n);
  e1.exponentModulo(publicKey.exponent(), n);
  check(publicKey.applyToValue(twoDigits) && twoDigits == e0 * n + e1,
        "the digits come out reversed, exactly as the reference writes them");

  // Text.
  const std::string text = publicKey.toString();
  check(RSAKey(text) == publicKey && RSAKey::fromString(privateKey.toString()) == privateKey,
        "toString and fromString round-trip both keys");
  check(text.find(',') != std::string::npos && text.compare(0, 6, "10001,") == 0,
        "the text is the reference's \"exponent,modulus\" in lower-case hex");

  // A signature made here, verified by the code that verifies real licences:
  // SHA-256 of a message, raised to d, checked as sig^e == hash by license.h.
  const std::string message = "core_crypto_test: signed by RSAKey, verified by license.h";
  uint8_t digest[32];
  sonore::license::sha256(message, digest);
  uint8_t littleEndian[32];
  for (int i = 0; i < 32; ++i) littleEndian[i] = digest[31 - i];
  BigInteger signature;
  signature.loadFromMemoryBlock(littleEndian, 32);
  check(privateKey.applyToValue(signature), "a SHA-256 digest signed with the private key");
  check(sonore::license::verifySignature(message, signature.toString(16), publicKey.toString()),
        "...which license.h's verifier accepts, reading the public key in the same text form");
  check(!sonore::license::verifySignature(message + ".", signature.toString(16), publicKey.toString()),
        "...and rejects for a changed message");
}

