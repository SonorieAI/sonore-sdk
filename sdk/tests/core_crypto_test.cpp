static void testMd5() {
  std::printf("\nMD5\n");
  using sonore::hash::md5Hex;
  // RFC 1321, appendix A.5: the whole suite.
  check(md5Hex("") == "d41d8cd98f00b204e9800998ecf8427e", "RFC 1321: \"\"");
  check(md5Hex("a") == "0cc175b9c0f1b6a831c399e269772661", "RFC 1321: \"a\"");
  check(md5Hex("abc") == "900150983cd24fb0d6963f7d28e17f72", "RFC 1321: \"abc\"");
  check(md5Hex("message digest") == "f96b697d7cb7938d525a2f31aaf161d0", "RFC 1321: \"message digest\"");
  check(md5Hex("abcdefghijklmnopqrstuvwxyz") == "c3fcd3d76192e4007dfb496cca67e13b",
        "RFC 1321: the alphabet");
  check(md5Hex("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789") ==
            "d174ab98d277d9f5a5611c2c9f419d9f",
        "RFC 1321: the 62 alphanumerics");
  check(md5Hex("12345678901234567890123456789012345678901234567890123456789012345678901234567890") ==
            "57edf4a22be3c955ac49da2e2107b67a",
        "RFC 1321: eighty digits");
  check(md5Hex(std::string(1000000, 'a')) == "7707d6ae4e027c70eea2a935c2296f21", "a million 'a's");

  bool boundaries = true;
  for (const BoundaryDigest& b : kBoundaries) {
    const std::vector<uint8_t> p = pattern(b.length);
    if (md5Hex(p.data(), p.size()) != b.md5) {
      std::printf("  (MD5 of %u bytes differs)\n", (unsigned) b.length);
      boundaries = false;
    }
  }
  check(boundaries, "every padding boundary (31..129 bytes) matches hashlib");

  // Streaming: any split of the input is the same digest.
  const std::vector<uint8_t> big = pattern(100003);
  check(md5Hex(big.data(), big.size()) == kPatternMd5, "100,003 bytes in one call");
  sonore::hash::MD5 m;
  size_t at = 0;
  while (at < big.size()) {
    const size_t take = (std::min)((size_t) (rng() % 200), big.size() - at);
    m.update(big.data() + at, take);
    at += take;
  }
  check(m.hex() == kPatternMd5, "...and the same in random pieces of 0 to 199 bytes");
  check(m.hex() == kPatternMd5, "finishing twice gives the same answer (finish works on a copy)");
  sonore::hash::MD5 more;
  more.update("a");
  (void) more.hex();
  more.update("bc");
  check(more.hex() == md5Hex("abc"), "...and appending after a finish carries on from where it was");
}

