  const std::vector<uint8_t> big = pattern(100003);
  const char* plain = sonoretest::tempPath("core-crypto-pattern.bin");
  // A name that is not ASCII, because a Windows path through the ANSI code
  // page is the bug pathio exists to stop. Joined by hand: tempPath goes
  // through std::filesystem, which would read these bytes as ANSI.
  std::string unicodeName(plain);
  unicodeName = unicodeName.substr(0, unicodeName.find_last_of("/\\") + 1) +
                "core-crypto-Jos\xC3\xA9-\xE9\x9F\xB3\xE6\xA5\xBD.bin";
  const char* unicode = unicodeName.c_str();
  check(writeFile(plain, big) && writeFile(unicode, big), "two copies of the pattern written");
  check(sonore::hash::md5File(plain) == kPatternMd5, "md5File streams it to the right digest");
  check(sonore::hash::whirlpoolFile(plain) == kPatternWhirlpool, "whirlpoolFile likewise");
  check(sonore::hash::sha256File(plain) == kPatternSha256, "sha256File likewise (now through streamFile)");
  check(sonore::hash::md5File(unicode) == kPatternMd5 && sonore::hash::whirlpoolFile(unicode) == kPatternWhirlpool,
        "...and through a UTF-8 path with an accent and CJK in it");
