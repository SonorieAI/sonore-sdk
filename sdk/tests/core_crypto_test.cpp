static int fails = 0;
static void check(bool ok, const char* what) {
  std::printf("  %s %s\n", ok ? "ok  " : "FAIL", what);
  if (!ok) ++fails;
}

static BigInteger parse(const char* text, int base) {
  BigInteger v;
  if (!v.parseString(text, base)) std::printf("  (could not parse \"%.40s\" in base %d)\n", text, base);
  return v;
}

static std::mt19937_64 rng(20261013);

/** A random value of up to `bits` bits, either sign when `signedToo`. */
static BigInteger randomBig(int bits, bool signedToo) {
  std::vector<uint8_t> bytes(((size_t) bits + 7) / 8);
  for (uint8_t& b : bytes) b = (uint8_t) rng();
  BigInteger v;
  v.loadFromMemoryBlock(bytes);
  v = v.getBitRange(0, bits);
  if (signedToo && (rng() & 1)) v.negate();
  return v;
}

static std::vector<uint8_t> fromHex(const char* hex) {
  std::vector<uint8_t> out;
  for (size_t i = 0; hex[i] && hex[i + 1]; i += 2) {
    auto nibble = [](char c) { return c <= '9' ? c - '0' : (c | 0x20) - 'a' + 10; };
    out.push_back((uint8_t) (nibble(hex[i]) * 16 + nibble(hex[i + 1])));
  }
  return out;
}

static std::string toHex(const uint8_t* bytes, size_t n) {
  static const char* digits = "0123456789abcdef";
  std::string s;
  for (size_t i = 0; i < n; ++i) {
    s += digits[bytes[i] >> 4];
    s += digits[bytes[i] & 15];
  }
  return s;
}

/** The fixed pattern the boundary digests were computed over. */
static std::vector<uint8_t> pattern(size_t n) {
  std::vector<uint8_t> p(n);
  for (size_t i = 0; i < n; ++i) p[i] = (uint8_t) ((i * 131 + 7) & 0xff);
  return p;
}

static bool writeFile(const char* path, const std::vector<uint8_t>& bytes) {
  FILE* f = sonore::pathio::open(path, "wb");
  if (!f) return false;
  const bool ok = std::fwrite(bytes.data(), 1, bytes.size(), f) == bytes.size();
  return std::fclose(f) == 0 && ok;
}

