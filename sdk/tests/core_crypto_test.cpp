// BigInteger (bigint.h), MD5 and Whirlpool (hash.h), BlowFish, RSAKey and
// Primes (crypto.h), checked against answers that did not come from them.
//
// Where the answers come from, because a test that compares code with itself
// proves only that it is consistent:
//
//   - MD5: the RFC 1321 test suite, plus digests of a fixed byte pattern from
//     Python's hashlib at every padding boundary.
//   - Whirlpool: the ISO/NESSIE vectors, plus the same pattern digests from
//     OpenSSL's implementation (`openssl dgst -whirlpool`).
//   - BlowFish: Eric Young's ECB set and the variable-key set, as Schneier
//     publishes them (each re-checked against OpenSSL before being pasted),
//     a buffer encrypted by `openssl enc -bf-ecb`, and its 1,042 pi words
//     recomputed here from Machin's formula.
//   - BigInteger: sums, products, quotients, gcds, powers and inverses
//     computed by Python's own integers; then identities on thousands of
//     random values; then modular exponentiation against license.h's BigInt,
//     an implementation written separately for a different job.
//   - Primes: a sieve below 50,000; known primes and composites; Carmichael
//     numbers, which fool a Fermat test by construction; strong pseudoprimes,
//     which fool Miller-Rabin to a fixed base set by construction.
//   - RSAKey: round trips at 512 and 1024 bits, and a signature made here
//     that license.h's verifier -- the code that checks real licences --
//     accepts.
