// Sonore SDK: the files a web editor's page brings with it.
//
// A page that is one string (SONORE_UI_HTML) has to carry everything inline:
// a 3D interface base64-encodes its library, its HDRI and its textures into
// the document, a module cannot `import` anything, and a loader cannot fetch
// a model. sonore_add_ui() compiles a FOLDER into the plugin instead -- the
// page, its scripts, images, fonts, models, wasm -- and every webview backend
// serves that folder at the page's own origin, so the page works the way a
// page on a web server does:
//
//   <script type="importmap">{"imports":{"three":"./three.module.min.js"}}</script>
//   <script type="module">
//     import * as THREE from "three";
//     new HDRLoader().load("studio.hdr", ...);   // fetched from the folder
//   </script>
//
// Nothing leaves the plugin: the origin is an address that never resolves
// (https://<plugin>.sonore.invalid/ on Windows, sonore-ui://<plugin>/ on
// WebKit), answered from these tables in memory. A path the folder does not
// have is a 404, and a path that tries to climb out of it ("..") is refused
// before it is looked up.
//
// The tables are generated by sonore_add_ui() (cmake/SonoreEmbedUi.cmake) as
// string literals, a few kilobytes each, which every compiler takes at any
// total size; this header only reads them.
#pragma once
#include <cstddef>
#include <cstdint>
#include <cstring>
#include <string>

namespace sonore {

/** One file of the page's folder, compiled into the plugin. */
struct UiAsset {
  /** Relative to the folder, '/'-separated, no leading slash ("js/app.js"). */
  const char* path;
  const unsigned char* data;
  size_t size;
};

/** The MIME type a file is served with, from its extension. A module script
 *  must be served as JavaScript or the browser refuses to run it, and wasm
 *  as application/wasm or streaming compilation refuses it; everything the
 *  table does not know is application/octet-stream, which is what a loader
 *  fetching bytes expects anyway. */
inline const char* uiMimeFor(const std::string& path) {
  const size_t dot = path.rfind('.');
  if (dot == std::string::npos || path.find('/', dot) != std::string::npos) return "application/octet-stream";
  std::string ext = path.substr(dot + 1);
  for (char& c : ext)
    if (c >= 'A' && c <= 'Z') c = (char) (c - 'A' + 'a');
  static const struct {
    const char* ext;
    const char* mime;
  } kTypes[] = {
      {"html", "text/html; charset=utf-8"},  {"htm", "text/html; charset=utf-8"},
      {"js", "text/javascript; charset=utf-8"}, {"mjs", "text/javascript; charset=utf-8"},
      {"css", "text/css; charset=utf-8"},    {"json", "application/json"},
      {"map", "application/json"},           {"txt", "text/plain; charset=utf-8"},
      {"xml", "application/xml"},            {"wasm", "application/wasm"},
      {"svg", "image/svg+xml"},              {"png", "image/png"},
      {"jpg", "image/jpeg"},                 {"jpeg", "image/jpeg"},
      {"webp", "image/webp"},                {"avif", "image/avif"},
      {"gif", "image/gif"},                  {"ico", "image/x-icon"},
      {"ktx2", "image/ktx2"},                {"hdr", "image/vnd.radiance"},
      {"exr", "image/x-exr"},                {"glb", "model/gltf-binary"},
      {"gltf", "model/gltf+json"},           {"woff", "font/woff"},
      {"woff2", "font/woff2"},               {"ttf", "font/ttf"},
      {"otf", "font/otf"},                   {"mp3", "audio/mpeg"},
      {"wav", "audio/wav"},                  {"ogg", "audio/ogg"},
      {"flac", "audio/flac"},                {"mp4", "video/mp4"},
  };
  for (const auto& t : kTypes)
    if (ext == t.ext) return t.mime;
  return "application/octet-stream";
}

/** A request's URL path as a key into the folder, or "" when it must be
 *  refused. The query and fragment are dropped, %XX is decoded, one leading
 *  '/' is optional, and a path that holds "..", ".", an empty segment, a
 *  backslash or a NUL is refused outright: a folder lookup is a string
 *  comparison, but a path that LOOKS like it climbs out is a bug or an
 *  attack either way, and answering it would only invite the next one. */
inline std::string uiAssetPath(const std::string& urlPath) {
  std::string in = urlPath.substr(0, urlPath.find_first_of("?#"));
  std::string out;
  out.reserve(in.size());
  for (size_t i = 0; i < in.size(); ++i) {
    char c = in[i];
    if (c == '%') {
      auto hex = [](char h) -> int {
        if (h >= '0' && h <= '9') return h - '0';
        if (h >= 'a' && h <= 'f') return h - 'a' + 10;
        if (h >= 'A' && h <= 'F') return h - 'A' + 10;
        return -1;
      };
      if (i + 2 >= in.size()) return std::string(); // a '%' needs two hex digits after it
      const int hi = hex(in[i + 1]), lo = hex(in[i + 2]);
      if (hi < 0 || lo < 0) return std::string();
      c = (char) (hi * 16 + lo);
      i += 2;
    }
    if (c == '\\' || c == '\0') return std::string();
    out += c;
  }
  if (!out.empty() && out[0] == '/') out.erase(0, 1);
  if (out.empty()) return std::string();
  size_t start = 0;
  while (start <= out.size()) {
    const size_t end = out.find('/', start);
    const std::string seg = out.substr(start, end == std::string::npos ? std::string::npos : end - start);
    if (seg.empty() || seg == "." || seg == "..") return std::string();
    if (end == std::string::npos) break;
    start = end + 1;
  }
  return out;
}

/** The host name a plugin's page is served under, from the plugin's id:
 *  the id's letters and digits lowered, the rest made hyphens (40 at most),
 *  then an FNV-1a hash of the whole id, so two ids that read alike stay
 *  apart. One per plugin, never per editor, because the address is the
 *  page's origin and an origin is what its localStorage is kept by: every
 *  Sonore editor shares one browser profile, so a shared address would hand
 *  one vendor's plugin another's stored settings. Every backend serves under
 *  this name, and Windows has since before there was a folder to serve, so
 *  it must not change: a different name is a page that forgot everything. */
inline std::string uiOriginLabel(const std::string& id) {
  std::string label;
  for (unsigned char c : id) {
    if (label.size() >= 40) break;
    if (c >= 'A' && c <= 'Z') c = (unsigned char) (c - 'A' + 'a');
    const bool keep = (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9');
    if (keep) label += (char) c;
    else if (!label.empty() && label.back() != '-') label += '-';
  }
  if (label.empty()) label = "plugin"; // a label may not start with a hyphen
  if (label.back() != '-') label += '-';
  uint32_t hash = 2166136261u; // stable across builds and runs
  for (unsigned char c : id) hash = (hash ^ c) * 16777619u;
  static const char kHex[] = "0123456789abcdef";
  for (int shift = 28; shift >= 0; shift -= 4) label += kHex[(hash >> shift) & 0xf];
  return label;
}

/** The scheme WebKit backends serve a page's folder under:
 *  sonore-ui://LABEL/editor.html and the folder beside it, LABEL being
 *  uiOriginLabel(id).
 *  (WebView2 cannot serve a scheme of its own to a page; it serves the same
 *  name under https://LABEL.sonore.invalid/.) */
constexpr const char* kUiScheme = "sonore-ui";

/** "sonore-ui://host/path?q" -> host and "/path?q". False, both empty, for
 *  any other address. */
inline bool uiSplitSchemeUrl(const std::string& uri, std::string& host, std::string& path) {
  const std::string prefix = std::string(kUiScheme) + "://";
  host.clear();
  path.clear();
  if (uri.compare(0, prefix.size(), prefix) != 0) return false;
  const size_t slash = uri.find('/', prefix.size());
  host = uri.substr(prefix.size(), slash == std::string::npos ? std::string::npos : slash - prefix.size());
  if (slash != std::string::npos) path = uri.substr(slash);
  return !host.empty();
}

/** The page's folder, as sonore_add_ui() compiled it. */
struct UiAssets {
  const UiAsset* items = nullptr;
  size_t count = 0;
  /** The page itself, when the folder supplies it (sonore_add_ui's ENTRY):
   *  then SONORE_UI_HTML is not needed at all. Null when it does not. */
  const char* entry = nullptr;

  /** The file a request for `urlPath` means, or null: not in the folder,
   *  or refused by uiAssetPath. */
  const UiAsset* find(const std::string& urlPath) const {
    const std::string key = uiAssetPath(urlPath);
    if (key.empty()) return nullptr;
    for (size_t i = 0; i < count; ++i)
      if (key == items[i].path) return &items[i];
    return nullptr;
  }

  /** The entry page's file, or null. */
  const UiAsset* entryAsset() const { return entry ? find(entry) : nullptr; }
};

/**
 * The folder the plugin's own editor serves.
 *
 * A backend asks for it when it opens a page, unless it was handed one
 * (setAssets), which is how a test serves a folder of its own. The plugin's
 * wrapper fills it in the first time it reads its page (clapwrap::uiHtml),
 * which every format does as it opens an editor, so it is set before any
 * backend looks. Null in a plugin with no folder: its page is one string, as
 * it always was.
 */
inline const UiAssets*& registeredUiAssets() {
  static const UiAssets* assets = nullptr;
  return assets;
}

} // namespace sonore
