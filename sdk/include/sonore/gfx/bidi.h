/** The base direction of a paragraph: given, or decided by its first
 *  strong character (Auto), as a text field does. */
enum class BidiDirection {
  LeftToRight, ///< Base level 0.
  RightToLeft, ///< Base level 1.
  Auto         ///< From the first strong character; left to right when there is none.
};

