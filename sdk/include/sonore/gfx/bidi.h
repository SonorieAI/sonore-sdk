/**
 * One paragraph's bidirectional levels, and the visual order of its lines.
 *
 *   BidiParagraph p(codepoints, n, BidiDirection::Auto);
 *   std::vector<int> order = p.visualOrder(0, n); // one line: all of it
 *
 * Even levels run left to right and odd ones right to left. A paragraph is
 * text up to a paragraph separator; a caller with several splits them first.
 */
class BidiParagraph {
public:
  /** Resolves the levels of `n` code points (UTF-32, not UTF-8) read as one
   *  paragraph. `text` is read here only and need not outlive the object.
   *  Allocates: run it off the audio thread. */
  BidiParagraph(const uint32_t* text, size_t n, BidiDirection direction) : n_(n) {
    detail::bidi::resolve(text, n, direction, resolved_);
  }

  /** 0 for a left-to-right paragraph, 1 for a right-to-left one. */
  int baseLevel() const { return resolved_.paragraphLevel; }

  /** The level of each character, before the line rules. A character the
   *  algorithm removes -- an embedding control, a zero-width BN -- has the
   *  level of its embedding. */
  const std::vector<uint8_t>& levels() const { return resolved_.levels; }

  /** The character removed from consideration by rule X9: it is not shown,
   *  and visualOrder leaves it out. */
  bool isRemoved(size_t i) const { return i < n_ && resolved_.removed[i] != 0; }

  /** The levels of the line [from, to) after rule L1. */
  std::vector<uint8_t> lineLevels(size_t from, size_t to) const {
    std::vector<uint8_t> out;
    if (from < to && to <= n_) detail::bidi::lineLevels(resolved_, from, to, out);
    return out;
  }

  /**
   * The line [from, to) in the order it is shown, left to right: indices
   * into the text, the removed characters left out. Rule L2: from the
   * highest level down to the lowest odd one, every run at that level or
   * above is reversed.
   */
  std::vector<int> visualOrder(size_t from, size_t to) const {
    std::vector<int> order;
    if (!(from < to && to <= n_)) return order;
    const std::vector<uint8_t> levels = lineLevels(from, to);
    std::vector<int> index;
    std::vector<uint8_t> lv;
    for (size_t k = 0; k < levels.size(); ++k) {
      if (resolved_.removed[from + k]) continue;
      index.push_back((int) (from + k));
      lv.push_back(levels[k]);
    }
    uint8_t highest = 0, lowestOdd = 255;
    for (uint8_t v : lv) {
      highest = (std::max)(highest, v);
      if (v & 1) lowestOdd = (std::min)(lowestOdd, v);
    }
    for (int level = highest; level >= (int) lowestOdd && level > 0; --level)
      for (size_t k = 0; k < lv.size();) {
        if (lv[k] < level) {
          ++k;
          continue;
        }
        size_t end = k;
        while (end < lv.size() && lv[end] >= level) ++end;
        std::reverse(index.begin() + (long) k, index.begin() + (long) end);
        std::reverse(lv.begin() + (long) k, lv.begin() + (long) end);
        k = end;
      }
    return index;
  }

  /** The character shown in place of `cp` in a right-to-left run: '(' for
   *  ')', and so on through Unicode's mirroring pairs. */
  static uint32_t mirrored(uint32_t cp) {
    for (const auto& m : detail::bidi::kMirrors)
      if (m[0] == cp) return m[1];
    return cp;
  }

private:
  size_t n_;
  detail::bidi::Resolved resolved_;
};

