// The Unicode Bidirectional Algorithm (UAX #9, Unicode 15): which way each
// character of a paragraph runs, and the order a line of it is shown in.
//
// ── Why a plugin needs it ───────────────────────────────────────────────────
//
// A preset named in Hebrew or Arabic, a sample folder, a user's own label:
// right-to-left text, often with numbers and Latin words inside it. Drawn in
// the order it is stored, every word of it reads backwards. The algorithm is
// what every operating system and browser applies, rule for rule, and a
// partial one is wrong in exactly the strings people notice -- a phone
// number inside Arabic, a bracket round a Latin word -- so this is all of it:
// explicit embeddings, overrides and isolates, the weak and neutral rules,
// bracket pairs, and the line rules. It is checked against the Unicode
// Consortium's own conformance file, every line of it.
//
// It knows nothing of fonts: it says which characters run which way and in
// what order the runs are shown. Shaping each run is gfx/text_shaper.h's job.
#pragma once

