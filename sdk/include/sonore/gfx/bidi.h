inline Class classOf(uint32_t cp) {
  if (cp > 0x10FFFF) return L;
  size_t lo = 0, hi = sizeof(kBidiRanges) / sizeof(kBidiRanges[0]);
  while (hi - lo > 1) {
    const size_t mid = (lo + hi) / 2;
    if ((kBidiRanges[mid] & 0xFFFFFFu) <= cp) lo = mid;
    else hi = mid;
  }
  return (Class) (kBidiRanges[lo] >> 24);
}

/** The bracket a character pairs with, and whether it opens; 0 when it is
 *  not a bracket. */
inline uint32_t bracketOf(uint32_t cp, bool* opens) {
  for (const auto& b : kBrackets)
    if (b[0] == cp) {
      *opens = b[2] != 0;
      return b[1];
    }
  return 0;
}

/** U+2329 and U+232A are canonically U+3008 and U+3009, and BD16 matches
 *  brackets by their canonical equivalents. */
inline uint32_t canonicalBracket(uint32_t cp) {
  return cp == 0x2329 ? 0x3008 : cp == 0x232A ? 0x3009 : cp;
}

inline bool isIsolateInitiator(Class c) { return c == LRI || c == RLI || c == FSI; }
inline bool isRemovedByX9(Class c) {
  return c == RLE || c == LRE || c == RLO || c == LRO || c == PDF || c == BN;
}
inline bool isNeutralOrIsolate(Class c) {
  return c == B || c == S || c == WS || c == ON || c == LRI || c == RLI || c == FSI || c == PDI;
}

/** P2 and P3 over [from, to): the first strong character's direction, not
 *  looking inside isolates; -1 when there is none. A matching PDI ends the
 *  search when `stopAtPdi`. */
inline int firstStrong(const std::vector<Class>& types, size_t from, size_t to, bool stopAtPdi) {
  int isolates = 0;
  for (size_t i = from; i < to; ++i) {
    const Class t = types[i];
    if (isIsolateInitiator(t)) {
      ++isolates;
    } else if (t == PDI) {
      if (isolates > 0) --isolates;
      else if (stopAtPdi) return -1;
    } else if (isolates == 0) {
      if (t == L) return 0;
      if (t == R || t == AL) return 1;
    }
    if (t == B) break;
  }
  return -1;
}

struct Resolved {
  std::vector<Class> original;  // as the character is
  std::vector<uint8_t> levels;
  std::vector<uint8_t> removed; // by X9: an embedding control, or BN
  int paragraphLevel = 0;
};

/** Every rule up to and including I2, for one paragraph. */
inline void resolve(const uint32_t* text, size_t n, BidiDirection direction, Resolved& out) {
  std::vector<Class>& original = out.original;
  original.resize(n);
  for (size_t i = 0; i < n; ++i) original[i] = classOf(text[i]);
  std::vector<Class> types = original;
  std::vector<uint8_t>& levels = out.levels;
  levels.assign(n, 0);
  out.removed.assign(n, 0);

  // BD9: each isolate initiator's matching PDI, or n.
  std::vector<size_t> matchingPdi(n, n), matchingInitiator(n, n);
  {
    std::vector<size_t> open;
    for (size_t i = 0; i < n; ++i) {
      if (isIsolateInitiator(types[i])) open.push_back(i);
      else if (types[i] == PDI && !open.empty()) {
        matchingPdi[open.back()] = i;
        matchingInitiator[i] = open.back();
        open.pop_back();
      } else if (types[i] == B) open.clear();
    }
  }

  // P2, P3.
  int paragraph = direction == BidiDirection::RightToLeft ? 1 : 0;
  if (direction == BidiDirection::Auto) {
    const int strong = firstStrong(types, 0, n, false);
    paragraph = strong < 0 ? 0 : strong;
  }
  out.paragraphLevel = paragraph;

  // X1-X8: the explicit levels.
  constexpr int kMaxDepth = 125;
  struct Entry {
    uint8_t level;
    Class override; // ON for none
    bool isolate;
  };
  std::vector<Entry> stack;
  stack.reserve(kMaxDepth + 2);
  stack.push_back({(uint8_t) paragraph, ON, false});
  int overflowIsolates = 0, overflowEmbeddings = 0, validIsolates = 0;
  for (size_t i = 0; i < n; ++i) {
    const Class t = types[i];
    const Entry top = stack.back();
    switch (t) {
      case RLE: case LRE: case RLO: case LRO: {
        const bool rtl = t == RLE || t == RLO;
        const int next = rtl ? ((top.level + 1) | 1) : ((top.level + 2) & ~1);
        if (next <= kMaxDepth && overflowIsolates == 0 && overflowEmbeddings == 0)
          stack.push_back({(uint8_t) next, t == RLO ? R : t == LRO ? L : ON, false});
        else if (overflowIsolates == 0)
          ++overflowEmbeddings;
        levels[i] = stack.back().level;
        break;
      }
      case RLI: case LRI: case FSI: {
        bool rtl = t == RLI;
        if (t == FSI) rtl = firstStrong(types, i + 1, matchingPdi[i], true) == 1;
        levels[i] = top.level;
        if (top.override != ON) types[i] = top.override;
        const int next = rtl ? ((top.level + 1) | 1) : ((top.level + 2) & ~1);
        if (next <= kMaxDepth && overflowIsolates == 0 && overflowEmbeddings == 0) {
          ++validIsolates;
          stack.push_back({(uint8_t) next, ON, true});
        } else {
          ++overflowIsolates;
        }
        break;
      }
      case PDI: {
        if (overflowIsolates > 0) {
          --overflowIsolates;
        } else if (validIsolates > 0) {
          overflowEmbeddings = 0;
          while (!stack.back().isolate && stack.size() > 1) stack.pop_back();
          if (stack.size() > 1) stack.pop_back();
          --validIsolates;
        }
        levels[i] = stack.back().level;
        if (stack.back().override != ON) types[i] = stack.back().override;
        break;
      }
      case PDF:
        if (overflowIsolates > 0) {
        } else if (overflowEmbeddings > 0) {
          --overflowEmbeddings;
        } else if (!stack.back().isolate && stack.size() >= 2) {
          stack.pop_back();
        }
        levels[i] = stack.back().level;
        break;
      case B:
        levels[i] = (uint8_t) paragraph;
        break;
      case BN:
        levels[i] = top.level;
        break;
      default:
        levels[i] = top.level;
        if (top.override != ON) types[i] = top.override;
        break;
    }
  }

  // X9: the embedding controls and BN take no further part.
  std::vector<size_t> kept;
  kept.reserve(n);
  for (size_t i = 0; i < n; ++i) {
    if (isRemovedByX9(original[i])) out.removed[i] = 1;
    else kept.push_back(i);
  }

  // X10: level runs, chained through isolates into isolating run sequences.
  std::vector<std::vector<size_t>> runs;
  for (size_t k = 0; k < kept.size(); ++k) {
    const size_t i = kept[k];
    if (runs.empty() || levels[runs.back().back()] != levels[i]) runs.push_back({});
    runs.back().push_back(i);
  }
  std::vector<std::vector<size_t>> sequences;
  {
    std::vector<int> runOf(n, -1);
    for (size_t r = 0; r < runs.size(); ++r)
      for (size_t i : runs[r]) runOf[i] = (int) r;
    std::vector<uint8_t> used(runs.size(), 0);
    for (size_t r = 0; r < runs.size(); ++r) {
      if (used[r]) continue;
      // A run starting with a PDI that matches an initiator continues that
      // initiator's sequence, and is reached from it.
      const size_t first = runs[r].front();
      if (original[first] == PDI && matchingInitiator[first] < n) continue;
      std::vector<size_t> seq;
      size_t at = r;
      for (;;) {
        used[at] = 1;
        seq.insert(seq.end(), runs[at].begin(), runs[at].end());
        const size_t last = runs[at].back();
        if (!isIsolateInitiator(original[last]) || matchingPdi[last] >= n) break;
        const int nextRun = runOf[matchingPdi[last]];
        if (nextRun < 0 || used[(size_t) nextRun]) break;
        at = (size_t) nextRun;
      }
      sequences.push_back(std::move(seq));
    }
    // Runs that start with a matched PDI whose initiator's run was never
    // reached -- not possible for a well-formed chain, but kept, not lost.
    for (size_t r = 0; r < runs.size(); ++r)
      if (!used[r]) sequences.push_back(runs[r]);
  }

  // W1-I2, per isolating run sequence. sos and eos come from the EMBEDDING
  // levels: I1 and I2 of a sequence already done must not move them.
  const std::vector<uint8_t> embedded = levels;
  for (const std::vector<size_t>& seq : sequences) {
    const size_t m = seq.size();
    const int level = embedded[seq.front()];
    // sos and eos: the higher of this level and the neighbouring one.
    auto keptNeighbour = [&](size_t index, int step) -> int {
      // The level of the nearest character not removed by X9, or -1.
      long j = (long) index + step;
      while (j >= 0 && j < (long) n) {
        if (!out.removed[(size_t) j]) return embedded[(size_t) j];
        j += step;
      }
      return -1;
    };
    const int before = keptNeighbour(seq.front(), -1);
    const int sosLevel = (std::max)(level, before < 0 ? paragraph : before);
    const size_t lastIndex = seq.back();
    // A sequence that ends on an isolate initiator ends at the paragraph's
    // level: what follows the initiator is inside the isolate.
    const int after = isIsolateInitiator(original[lastIndex]) ? paragraph : keptNeighbour(lastIndex, 1);
    const int eosLevel = (std::max)(level, after < 0 ? paragraph : after);
    const Class sos = (sosLevel & 1) ? R : L;
    const Class eos = (eosLevel & 1) ? R : L;

    std::vector<Class> t(m);
    for (size_t k = 0; k < m; ++k) t[k] = types[seq[k]];

    // W1.
    for (size_t k = 0; k < m; ++k)
      if (t[k] == NSM) {
        if (k == 0) t[k] = sos;
        else t[k] = (isIsolateInitiator(t[k - 1]) || t[k - 1] == PDI) ? ON : t[k - 1];
      }
    // W2.
    {
      Class strong = sos;
      for (size_t k = 0; k < m; ++k) {
        if (t[k] == L || t[k] == R || t[k] == AL) strong = t[k];
        else if (t[k] == EN && strong == AL) t[k] = AN;
      }
    }
    // W3.
    for (size_t k = 0; k < m; ++k)
      if (t[k] == AL) t[k] = R;
    // W4.
    for (size_t k = 1; k + 1 < m; ++k) {
      if (t[k] == ES && t[k - 1] == EN && t[k + 1] == EN) t[k] = EN;
      else if (t[k] == CS && t[k - 1] == EN && t[k + 1] == EN) t[k] = EN;
      else if (t[k] == CS && t[k - 1] == AN && t[k + 1] == AN) t[k] = AN;
    }
    // W5.
    for (size_t k = 0; k < m; ++k) {
      if (t[k] != ET) continue;
      size_t end = k;
      while (end < m && t[end] == ET) ++end;
      const bool touches = (k > 0 && t[k - 1] == EN) || (end < m && t[end] == EN);
      if (touches)
        for (size_t j = k; j < end; ++j) t[j] = EN;
      k = end - 1;
    }
    // W6.
    for (size_t k = 0; k < m; ++k)
      if (t[k] == ES || t[k] == ET || t[k] == CS) t[k] = ON;
    // W7.
    {
      Class strong = sos;
      for (size_t k = 0; k < m; ++k) {
        if (t[k] == L || t[k] == R) strong = t[k];
        else if (t[k] == EN && strong == L) t[k] = L;
      }
    }

    // N0: bracket pairs.
    {
      struct Pair {
        size_t open, close;
      };
      std::vector<Pair> pairs;
      struct Opener {
        uint32_t closer;
        size_t at;
      };
      std::vector<Opener> openers;
      bool overflow = false;
      for (size_t k = 0; k < m && !overflow; ++k) {
        if (t[k] != ON) continue;
        bool opens = false;
        const uint32_t cp = text[seq[k]];
        const uint32_t partner = bracketOf(cp, &opens);
        if (!partner) continue;
        if (opens) {
          if (openers.size() >= 63) {
            overflow = true;
            break;
          }
          openers.push_back({canonicalBracket(partner), k});
        } else {
          const uint32_t self = canonicalBracket(cp);
          for (size_t s = openers.size(); s-- > 0;)
            if (openers[s].closer == self) {
              pairs.push_back({openers[s].at, k});
              openers.resize(s);
              break;
            }
        }
      }
      if (overflow) pairs.clear();
      std::sort(pairs.begin(), pairs.end(),
                [](const Pair& a, const Pair& b) { return a.open < b.open; });
      const Class embedding = (level & 1) ? R : L;
      auto strongOf = [](Class c) -> Class {
        if (c == L) return L;
        if (c == R || c == EN || c == AN) return R;
        return ON;
      };
      for (const Pair& p : pairs) {
        bool sameInside = false, oppositeInside = false;
        for (size_t k = p.open + 1; k < p.close; ++k) {
          const Class s = strongOf(t[k]);
          if (s == ON) continue;
          if (s == embedding) sameInside = true;
          else oppositeInside = true;
        }
        Class chosen = ON;
        if (sameInside) {
          chosen = embedding;
        } else if (oppositeInside) {
          Class context = sos;
          for (size_t k = p.open; k-- > 0;) {
            const Class s = strongOf(t[k]);
            if (s != ON) {
              context = s;
              break;
            }
          }
          chosen = context != embedding ? context : embedding;
        }
        if (chosen == ON) continue;
        t[p.open] = t[p.close] = chosen;
        // An NSM that W1 made a neutral after a bracket follows the bracket.
        for (size_t at : {p.open, p.close})
          for (size_t k = at + 1; k < m && original[seq[k]] == NSM; ++k) t[k] = chosen;
      }
    }

    // N1, N2.
    for (size_t k = 0; k < m; ++k) {
      if (!isNeutralOrIsolate(t[k])) continue;
      size_t end = k;
      while (end < m && isNeutralOrIsolate(t[end])) ++end;
      auto dir = [](Class c) { return c == L ? L : R; }; // EN and AN count as R
      const Class leading = k == 0 ? sos : dir(t[k - 1]);
      const Class trailing = end == m ? eos : dir(t[end]);
      const Class fill = leading == trailing ? leading : ((level & 1) ? R : L);
      for (size_t j = k; j < end; ++j) t[j] = fill;
      k = end - 1;
    }

    // I1, I2.
    for (size_t k = 0; k < m; ++k) {
      uint8_t& lv = levels[seq[k]];
      if ((lv & 1) == 0) {
        if (t[k] == R) lv += 1;
        else if (t[k] == AN || t[k] == EN) lv += 2;
      } else if (t[k] == L || t[k] == EN || t[k] == AN) {
        lv += 1;
      }
    }
  }
}

/** L1 for the line [from, to): separators, and the whitespace and isolate
 *  controls before them and at the end of the line, go back to the
 *  paragraph's level. */
inline void lineLevels(const Resolved& r, size_t from, size_t to, std::vector<uint8_t>& out) {
  out.assign(r.levels.begin() + (long) from, r.levels.begin() + (long) to);
  auto trailing = [&](Class c) {
    return c == WS || c == FSI || c == LRI || c == RLI || c == PDI || isRemovedByX9(c);
  };
  bool resetting = true; // from the end of the line backwards
  for (size_t k = to - from; k-- > 0;) {
    const Class c = r.original[from + k];
    if (c == S || c == B) {
      out[k] = (uint8_t) r.paragraphLevel;
      resetting = true;
    } else if (resetting && trailing(c)) {
      out[k] = (uint8_t) r.paragraphLevel;
    } else {
      resetting = false;
    }
  }
}

