/** A code point's class, and its flags: 0x40 an East Asian bracket, 0x80 an
 *  unassigned pictographic code point. */
inline uint8_t valueOf(uint32_t cp) {
  if (cp > 0x10FFFF) return kAL;
  size_t lo = 0, hi = sizeof(kLineBreakRanges) / sizeof(kLineBreakRanges[0]);
  while (hi - lo > 1) {
    const size_t mid = (lo + hi) / 2;
    if ((kLineBreakRanges[mid] & 0xFFFFFFu) <= cp) lo = mid;
    else hi = mid;
  }
  return (uint8_t) (kLineBreakRanges[lo] >> 24);
}

inline bool hardOrSpace(uint8_t c) { return c == kBK || c == kCR || c == kLF || c == kNL || c == kSP || c == kZW; }

