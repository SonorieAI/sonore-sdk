/** Whether a line may end before a character. */
enum class LineBreak : uint8_t {
  None,     ///< The line may not end here.
  Allowed,  ///< A wrap may end the line here.
  Mandatory ///< The line ends here: after a hard line break, and at the end.
};

/**
 * The line breaks of `text`, one for each of its n + 1 boundaries: [i] is
 * the one before character i. Never at the start (LB2), always at the end
 * (LB3), after a hard line break mandatory.
 */
inline std::vector<LineBreak> findLineBreaks(const uint32_t* text, size_t n) {
  using namespace detail::linebreak;
  std::vector<LineBreak> out(n + 1, LineBreak::None);
  if (n == 0) return out;
  out[n] = LineBreak::Mandatory;
  std::vector<uint8_t> raw(n), flags(n), cls(n);
  std::vector<size_t> unit(n); // the character each one's unit begins with
  for (size_t i = 0; i < n; ++i) {
    const uint8_t v = valueOf(text[i]);
    raw[i] = v & 0x3F;
    flags[i] = v & 0xC0;
    // LB9 and LB10: a combining mark or ZWJ after anything but a hard break,
    // a space or ZW is part of what it follows and takes its class; any
    // other is a letter.
    const bool combining = raw[i] == kCM || raw[i] == kZWJ;
    if (combining && i > 0 && !hardOrSpace(raw[i - 1])) {
      unit[i] = unit[i - 1];
      cls[i] = cls[i - 1];
    } else {
      unit[i] = i;
      cls[i] = combining ? (uint8_t) kAL : raw[i];
    }
  }
  // Per unit, read once in order rather than walked back over at every
  // boundary -- 80,000 flags took six seconds that way: whether the units up
  // to it, it included, end a number (a NU then any number of NU, SY and
  // IS), and how many regional indicators in a row end with it.
  std::vector<uint8_t> numbers(n, 0);
  std::vector<size_t> indicators(n, 0);
  for (size_t u = 0; u < n; ++u) {
    if (unit[u] != u) continue;
    const size_t previous = u > 0 ? unit[u - 1] : 0;
    if (cls[u] == kNU) numbers[u] = 1;
    else if ((cls[u] == kSY || cls[u] == kIS) && u > 0) numbers[u] = numbers[previous];
    if (cls[u] == kRI) indicators[u] = 1 + (u > 0 ? indicators[previous] : 0);
  }
  auto numberRun = [&](size_t u) { return numbers[unit[u]] != 0; };
  // UAX #14's Example 7, for the boundary after unit `before` and before
  // character i: (PR|PO) x (OP|HY)? NU; (OP|HY) x NU; NU x (NU|SY|IS);
  // NU (NU|SY|IS)* x (NU|SY|IS|CL|CP); NU (NU|SY|IS)* (CL|CP)? x (PO|PR).
  auto number = [&](size_t before, size_t i) {
    const uint8_t A = cls[before], B = cls[i];
    if ((A == kPR || A == kPO) && B == kNU) return true;
    if ((A == kPR || A == kPO) && (B == kOP || B == kHY)) {
      size_t j = i + 1;
      while (j < n && unit[j] == i) ++j;
      if (j < n && cls[j] == kNU) return true;
    }
    if ((A == kOP || A == kHY) && B == kNU) return true;
    if ((B == kNU || B == kSY || B == kIS || B == kCL || B == kCP) && numberRun(before)) return true;
    if (B == kPO || B == kPR) {
      if (numberRun(before)) return true;
      if ((A == kCL || A == kCP) && before > 0 && numberRun(unit[before - 1])) return true;
    }
    return false;
  };
  for (size_t i = 1; i < n; ++i) {
    const uint8_t a = raw[i - 1], b = raw[i];
    LineBreak& here = out[i];
    // LB4, LB5: hard line breaks.
    if (a == kBK || ((a == kCR && b != kLF) || a == kLF || a == kNL)) {
      here = LineBreak::Mandatory;
      continue;
    }
    // LB5, LB6, LB7: not inside CR LF, not before a hard break, a space or ZW.
    if (a == kCR || b == kBK || b == kCR || b == kLF || b == kNL || b == kSP || b == kZW) continue;
    // The class before any spaces that end the text so far.
    size_t k = i;
    while (k > 0 && raw[k - 1] == kSP) --k;
    // LB8: after ZW, even across spaces.
    if (k > 0 && raw[k - 1] == kZW) {
      here = LineBreak::Allowed;
      continue;
    }
    // LB8a: not after ZWJ. LB9: not inside a unit.
    if (a == kZWJ || unit[i] != i) continue;
    const uint8_t A = cls[i - 1], B = cls[i];
    const size_t before = unit[i - 1];
    const uint8_t spaced = k > 0 ? cls[k - 1] : (uint8_t) 0xFF;
    bool keep;
    if (A == kWJ || B == kWJ) keep = true;                                         // LB11
    else if (A == kGL) keep = true;                                                // LB12
    else if (B == kGL && A != kSP && A != kBA && A != kHY) keep = true;           // LB12a
    else if (B == kEX || (A != kNU && (B == kCL || B == kCP || B == kIS || B == kSY))) keep = true; // LB13, tailored
    else if (spaced == kOP) keep = true;                                           // LB14
    else if (B == kOP && spaced == kQU) keep = true;                               // LB15
    else if (B == kNS && (spaced == kCL || spaced == kCP)) keep = true;            // LB16
    else if (B == kB2 && spaced == kB2) keep = true;                               // LB17
    else if (A == kSP) keep = false;                                               // LB18
    else if (A == kQU || B == kQU) keep = true;                                    // LB19
    else if (A == kCB || B == kCB) keep = false;                                   // LB20
    else if (B == kBA || B == kHY || B == kNS || A == kBB) keep = true;            // LB21
    else if ((A == kHY || A == kBA) && before > 0 && cls[before - 1] == kHL) keep = true; // LB21a
    else if (A == kSY && B == kHL) keep = true;                                    // LB21b
    else if (B == kIN) keep = true;                                                // LB22
    else if (((A == kAL || A == kHL) && B == kNU) || (A == kNU && (B == kAL || B == kHL))) keep = true; // LB23
    else if ((A == kPR && (B == kID || B == kEB || B == kEM)) ||
             ((A == kID || A == kEB || A == kEM) && B == kPO))
      keep = true; // LB23a
    else if (((A == kPR || A == kPO) && (B == kAL || B == kHL)) ||
             ((A == kAL || A == kHL) && (B == kPR || B == kPO)))
      keep = true; // LB24
    else if (number(before, i)) keep = true; // LB25, as the numbers' tailoring
    else if ((A == kJL && (B == kJL || B == kJV || B == kH2 || B == kH3)) ||
             ((A == kJV || A == kH2) && (B == kJV || B == kJT)) || ((A == kJT || A == kH3) && B == kJT))
      keep = true; // LB26
    else if (((A == kJL || A == kJV || A == kJT || A == kH2 || A == kH3) && B == kPO) ||
             (A == kPR && (B == kJL || B == kJV || B == kJT || B == kH2 || B == kH3)))
      keep = true; // LB27
    else if ((A == kAL || A == kHL) && (B == kAL || B == kHL)) keep = true;        // LB28
    else if (A == kIS && (B == kAL || B == kHL)) keep = true;                      // LB29
    else if (((A == kAL || A == kHL || A == kNU) && B == kOP && !(flags[i] & 0x40)) ||
             (A == kCP && !(flags[before] & 0x40) && (B == kAL || B == kHL || B == kNU)))
      keep = true; // LB30
    else if (A == kRI && B == kRI) {
      // LB30a: regional indicators pair up; an odd count before keeps this one.
      keep = (indicators[before] & 1) != 0;
    } else if (B == kEM && (A == kEB || (flags[before] & 0x80))) keep = true;     // LB30b
    else keep = false;                                                             // LB31
    if (!keep) here = LineBreak::Allowed;
  }
  return out;
}

