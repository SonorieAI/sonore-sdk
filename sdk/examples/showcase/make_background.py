# Regenerates background.h: the showcase editor's backdrop, a small JPEG
# compiled into the plugin as bytes.
#
#   python make_background.py      (needs Pillow; writes background.h beside it)
#
# Why a generated texture and not a photograph: it has to be ours to ship, and
# it has to be SMALL -- every byte here is in every copy of the binary. A
# blurred, dark, low-detail picture is what JPEG compresses best, and it is
# drawn under a tint of the colour scheme, so it only has to give the panel
# some depth, not carry detail.
import math
import os
import random
from io import BytesIO

from PIL import Image, ImageDraw, ImageFilter

W, H = 320, 205
rng = random.Random(7)  # fixed seed: the same bytes on every run

img = Image.new("RGB", (W, H))
px = img.load()
for y in range(H):
    for x in range(W):
        # A cool vertical gradient, lit from the top left.
        t = y / (H - 1)
        d = math.hypot(x - W * 0.2, y - H * 0.1) / math.hypot(W, H)
        glow = max(0.0, 0.55 - d) * 70
        base = (34 - 18 * t + glow, 42 - 22 * t + glow * 1.05, 50 - 24 * t + glow * 1.2)
        px[x, y] = tuple(int(max(0, min(255, c))) for c in base)

# Brushed metal: horizontal streaks of noise, smeared sideways.
noise = Image.new("L", (W, H))
npx = noise.load()
for y in range(H):
    for x in range(W):
        npx[x, y] = int(128 + rng.gauss(0, 30))
noise = noise.resize((W // 8, H), Image.BILINEAR).resize((W, H), Image.BILINEAR)
img = Image.blend(img, Image.merge("RGB", (noise, noise, noise)), 0.06)

# A few faint sine traces across the panel: it is a waveshaper.
draw = ImageDraw.Draw(img)
for k, (amp, period, phase, shade) in enumerate([(22, 140, 0.0, 60), (14, 90, 1.3, 52), (30, 210, 2.1, 46)]):
    pts = [(x, H * (0.55 + 0.1 * k) + amp * math.sin(2 * math.pi * x / period + phase)) for x in range(W)]
    draw.line(pts, fill=(shade, shade + 8, shade + 14), width=1)
img = img.filter(ImageFilter.GaussianBlur(0.8))

buf = BytesIO()
img.save(buf, "JPEG", quality=85, optimize=True)
data = buf.getvalue()

lines = []
for i in range(0, len(data), 20):
    lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 20]) + ",")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "background.h")
with open(out, "w", newline="\n") as f:
    f.write("// SPDX-License-Identifier: Apache-2.0\n")
    f.write("// Generated by make_background.py -- a %dx%d JPEG, %d bytes. Do not edit;\n" % (W, H, len(data)))
    f.write("// run the script again instead.\n")
    f.write("#pragma once\n\n")
    f.write("static const unsigned char kBackgroundJpeg[] = {\n")
    f.write("\n".join(lines))
    f.write("\n};\n")
print("wrote", out, len(data), "bytes")
